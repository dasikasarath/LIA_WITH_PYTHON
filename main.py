@app.post("/ask", response_model=AskResponse, tags=["RAG"])
async def ask_question(quest: Quest):
    """
    RAG Query Endpoint (Non-streaming):
    Accepts question and optional conversation_id (or conversationId).
    Runs retrieval and synthesis asynchronously off the main event loop for high throughput.
    """
    if not quest.question or not quest.question.strip():
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="The 'question' field must not be empty."
        )

    conv_id = ai_service.resolve_conversation_id(quest.conversationId)
    # Offload blocking operations to threadpool so event loop remains responsive
    try:
        answer, sources, retrieved_count = await asyncio.to_thread(
            ai_service.searchres_with_details,
            quest.question,
            conv_id
        )
    except Exception as e:
        logger.error(f"Error during ask_question: {e}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to generate answer: {str(e)}"
        )

    return AskResponse(
        answer=answer,
        conversation_id=conv_id,
        sources=sources,
        retrieved_count=retrieved_count
    )

@app.post("/ask/stream", tags=["RAG"])
async def ask_question_stream(quest: Quest):
    """
    Real-time Streaming RAG Endpoint:
    Streams SSE tokens directly to the client as they are generated by Gemini.
    """
    if not quest.question or not quest.question.strip():
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="The 'question' field must not be empty."
        )

    conv_id = ai_service.resolve_conversation_id(quest.conversationId)

    def sync_stream_generator():
        try:
            for event_type, data in ai_service.searchres_stream(quest.question, conv_id):
                payload = json.dumps({"type": event_type, "data": data})
                yield f"data: {payload}\n\n"
        except Exception as e:
            logger.error(f"Stream generation error: {e}", exc_info=True)
            err_payload = json.dumps({"type": "error", "data": str(e)})
            yield f"data: {err_payload}\n\n"

    return StreamingResponse(
        sync_stream_generator(),
        media_type="text/event-stream",
        headers={
            "Cache-Control": "no-cache",
            "Connection": "keep-alive",
            "X-Accel-Buffering": "no"
        }
    )

@app.post("/upload-pdf", response_model=UploadResponse, tags=["Document Ingestion"])
async def upload_pdf(file: UploadFile = File(...)):
    """
    PDF Ingestion Endpoint:
    Upload a PDF file (up to 50MB) to extract text, chunk, embed with Gemini, and store in pgvector.
    """
    if not file.filename.lower().endswith(".pdf"):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Only PDF files (.pdf) are accepted."
        )

    # Read file content
    contents = await file.read()
    max_bytes = settings.max_upload_size_mb * 1024 * 1024
    if len(contents) > max_bytes:
        raise HTTPException(
            status_code=status.HTTP_413_REQUEST_ENTITY_TOO_LARGE,
            detail=f"File exceeds the maximum allowed size of {settings.max_upload_size_mb}MB."
        )

    try:
        pages, chunks, parent_id = pdf_service.process_pdf(contents, file.filename)
        return UploadResponse(
            message=f"Successfully indexed '{file.filename}' into vector database.",
            filename=file.filename,
            pages_processed=pages,
            chunks_stored=chunks,
            parent_document_id=parent_id
        )
    except Exception as e:
        logger.error(f"Error processing PDF '{file.filename}': {e}", exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to process PDF: {str(e)}"
        )

@app.post("/clear-memory", response_model=MemoryClearResponse, tags=["Memory"])
async def clear_conversation_memory(req: MemoryClearRequest):
    """Clears multi-turn conversation memory for the given conversation_id."""
    conv_id = ai_service.resolve_conversation_id(req.conversation_id)
    ai_service.clear_memory(conv_id)
    return MemoryClearResponse(
        message=f"Conversation memory for '{conv_id}' cleared successfully.",
        conversation_id=conv_id,
        status="success"
    )

@app.delete("/memory/{conversation_id}", response_model=MemoryClearResponse, tags=["Memory"])
async def delete_conversation_memory(conversation_id: str):
    """Clears memory for path-specified conversation_id."""
    conv_id = ai_service.resolve_conversation_id(conversation_id)
    ai_service.clear_memory(conv_id)
    return MemoryClearResponse(
        message=f"Conversation memory for '{conv_id}' cleared successfully.",
        conversation_id=conv_id,
        status="success"
    )

